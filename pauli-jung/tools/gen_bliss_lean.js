#!/usr/bin/env node
// Generate Bliss/Data.lean from the Blissymbol database (../blissdata_*.js).
//
//   node tools/gen_bliss_lean.js
//
// Shapes and characters become one list of "items", ordered so that every
// item only refers to items before it; words likewise. Lean then checks
// that ordering, which is what makes every symbol resolvable to primitive
// paths. Coordinates are stored in thousandths of a unit.
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..', '..');
const ctx = {};
vm.createContext(ctx);
for (const f of ['blissdata_chars.js', 'blissdata_words.js'])
  vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx);
const C = vm.runInContext('BLISS_CHAR_DATA', ctx), W = vm.runInContext('BLISS_WORD_DATA', ctx);

const milli = v => Math.round((v || 0) * 1000);
const int = n => (n < 0 ? `(${n})` : `${n}`);
const str = s => JSON.stringify(s);

// Primitive paths.
const primNames = Object.keys(C.paths).sort();
const primIdx = new Map(primNames.map((n, i) => [n, i]));

// Items: shapes and chars, topologically sorted. Keys are tagged because a
// shape and a char could in principle share a name.
const itemKeys = [], itemIdx = new Map(), visiting = new Set();
const itemDef = key => key[0] === 's' ? C.shapes[key.slice(2)] : C.chars[key.slice(2)].d;
function visitItem(key) {
  if (itemIdx.has(key)) return;
  if (visiting.has(key)) throw new Error('cycle through ' + key);
  visiting.add(key);
  for (const part of itemDef(key)) {
    if (part.d in C.shapes) visitItem('s:' + part.d);
    else if (!(part.d in C.paths)) throw new Error(`${key}: unknown part ${part.d}`);
  }
  visiting.delete(key);
  itemIdx.set(key, itemKeys.length);
  itemKeys.push(key);
}
Object.keys(C.shapes).sort().forEach(n => visitItem('s:' + n));
const charNames = Object.keys(C.chars).sort();
charNames.forEach(n => visitItem('c:' + n));
const charIdx = new Map(charNames.map((n, i) => [n, i]));

const refLean = part => part.d in C.shapes
  ? `.item ${itemIdx.get('s:' + part.d)} ${int(milli(part.x))} ${int(milli(part.y))}`
  : `.prim ${primIdx.get(part.d)} ${int(milli(part.x))} ${int(milli(part.y))}`;
const itemLines = itemKeys.map(k => `[${itemDef(k).map(refLean).join(', ')}]`);

// Words, topologically sorted. A component names a word if one exists
// (and is not the word itself), else a character: the viewer's rule.
const wordKeys = [], wordIdx = new Map(), wVisiting = new Set();
const isWordRef = (owner, n) => n in W.words && n !== owner;
function visitWord(name) {
  if (wordIdx.has(name)) return;
  if (wVisiting.has(name)) throw new Error('word cycle through ' + name);
  wVisiting.add(name);
  for (const part of W.words[name]) {
    if (isWordRef(name, part)) visitWord(part);
    else if (!charIdx.has(part)) throw new Error(`${name}: unknown part ${part}`);
  }
  wVisiting.delete(name);
  wordIdx.set(name, wordKeys.length);
  wordKeys.push(name);
}
Object.keys(W.words).sort().forEach(visitWord);
const wordLines = wordKeys.map(n =>
  `(${str(n)}, [${W.words[n].map(p => isWordRef(n, p) ? `.word ${wordIdx.get(p)}` : `.char ${charIdx.get(p)}`).join(', ')}])`);

function chunked(name, type, lines, size) {
  const out = [], names = [];
  for (let i = 0; i < lines.length; i += size) {
    const nm = `${name}Chunk${i / size}`;
    names.push(nm);
    out.push(`def ${nm} : List ${type} := [\n  ${lines.slice(i, i + size).join(',\n  ')}]\n`);
  }
  out.push(`/-- All ${name}, in dependency order. -/\ndef ${name} : List ${type} :=\n  ${names.join(' ++ ')}\n`);
  return out.join('\n');
}

const lean = `import Bliss.Basic

/-!
# The Blissymbol database

**Generated** by \`tools/gen_bliss_lean.js\` from \`blissdata_chars.js\` and
\`blissdata_words.js\`. Do not edit by hand.

${primNames.length} primitive paths, ${itemKeys.length} items (${Object.keys(C.shapes).length} shapes and ${charNames.length} characters),
${wordKeys.length} words.
-/

namespace Bliss

/-- Names of the primitive paths. -/
def primNames : List String := [
  ${primNames.map(str).join(',\n  ')}]

${chunked('items', 'Item', itemLines, 150)}
/-- The characters: name, item, width and height (thousandths). -/
def chars : List CharEntry := [
  ${charNames.map(n => `⟨${str(n)}, ${itemIdx.get('c:' + n)}, ${int(milli(C.chars[n].w))}, ${int(milli(C.chars[n].h))}⟩`).join(',\n  ')}]

${chunked('words', '(String × List WRef)', wordLines, 250)}
end Bliss
`;
const out = path.join(__dirname, '..', 'Bliss', 'Data.lean');
fs.writeFileSync(out, lean);
// Geometry of the primitive paths, for the 3D viewer (index = Lean's prim index).
const pathsOut = path.join(root, 'bliss3d', 'bliss3d_paths.js');
fs.mkdirSync(path.dirname(pathsOut), { recursive: true });
fs.writeFileSync(pathsOut,
  '// Generated by pauli-jung/tools/gen_bliss_lean.js from blissdata_chars.js. Do not edit.\n' +
  'var BLISS3D_PATHS = [\n' + primNames.map(n => JSON.stringify(C.paths[n])).join(',\n') + '\n];\n');
console.log(`wrote ${out}: ${primNames.length} prims, ${itemKeys.length} items, ${charNames.length} chars, ${wordKeys.length} words`);
