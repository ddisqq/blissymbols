"""
Generate the Common Lisp data and test fixtures for the `bliss` library in lisp/.

  lisp/src/data.lisp        the whole Blissymbol database as Lisp literals
  lisp/tests/fixtures.lisp  expected layouts computed by the Python port (tools/bliss_core.py)

Run:  python3 tools/build_lisp.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bliss_core as bc  # noqa: E402

REPO = bc.REPO


def lstr(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    if isinstance(v, bool):
        raise TypeError(v)
    if isinstance(v, int):
        return str(v)
    s = repr(float(v))
    return s.replace("e", "d") if "e" in s else s + "d0"


def emit_data(chardata, worddata):
    out = []
    w = out.append
    w(";;;; GENERATED by tools/build_lisp.py from blissdata_chars.js and blissdata_words.js. Do not edit.\n")
    w("(in-package #:bliss)\n")

    w("(defparameter *raw-chars*")
    w(" '(")
    for name, c in chardata["chars"].items():
        parts = " ".join(f"({lstr(p['d'])} {num(p.get('x', 0))} {num(p.get('y', 0))})" for p in c.get("d", []))
        h = num(c["h"]) if "h" in c else "nil"
        w(f"  ({lstr(name)} {num(c['w'])} {h} ({parts}))")
    w(" ))\n")

    def alist(title, table):
        w(f"(defparameter {title}")
        w(" '(" + " ".join(f"({lstr(k)} . {num(v)})" for k, v in table.items()) + "))\n")

    alist("*raw-center*", chardata["center"])
    alist("*raw-kerning-left*", chardata["kerning_left"])
    alist("*raw-kerning-right*", chardata["kerning_right"])

    w("(defparameter *raw-paths*")
    w(" '(")
    for name, p in chardata["paths"].items():
        fields = []
        for k, v in p.items():
            val = lstr(v) if isinstance(v, str) else num(v)
            fields.append(f"({lstr(k)} . {val})")
        w(f"  ({lstr(name)} {' '.join(fields)})")
    w(" ))\n")

    w("(defparameter *raw-shapes*")
    w(" '(")
    for name, items in chardata["shapes"].items():
        parts = " ".join(f"({lstr(p['d'])} {num(p.get('x', 0))} {num(p.get('y', 0))})" for p in items)
        w(f"  ({lstr(name)} {parts})")
    w(" ))\n")

    w("(defparameter *raw-words*")
    w(" '(")
    for key, comps in worddata["words"].items():
        w(f"  ({lstr(key)} " + " ".join(lstr(c) for c in comps) + ")")
    w(" ))\n")
    return "\n".join(out)


def emit_fixtures(B, words, chars):
    from build_poem import resolve
    names = ["friend", "habit", "Haggadah", "aboard", "accident", "man", "a_(lowercase)",
             "A_(uppercase)", "abortion_(induced)", "sun", "heart", "house", "happy", "walk", "no"]
    lines = [";;;; GENERATED by tools/build_lisp.py: layouts computed by the Python port. Do not edit.\n",
             "(in-package #:bliss)\n",
             "(defparameter *expected-layouts*", " '("]
    for name in names:
        key = resolve(name, chars, words)
        exp = B.expand_word([key])
        items = " ".join(f"({lstr(p['d'])} {num(p['x'])} {num(p['y'])})" for p in exp["chars"])
        lines.append(f"  ({lstr(key)} {num(exp['left'])} {num(exp['right'])} ({items}))")
    lines.append(" ))\n")
    return "\n".join(lines)


def main():
    chardata, worddata = bc.load_data()
    B = bc.Bliss(chardata, worddata)
    os.makedirs(os.path.join(REPO, "lisp", "src"), exist_ok=True)
    os.makedirs(os.path.join(REPO, "lisp", "tests"), exist_ok=True)
    with open(os.path.join(REPO, "lisp", "src", "data.lisp"), "w", encoding="utf8") as f:
        f.write(emit_data(chardata, worddata))
    with open(os.path.join(REPO, "lisp", "tests", "fixtures.lisp"), "w", encoding="utf8") as f:
        f.write(emit_fixtures(B, worddata["words"], chardata["chars"]))
    print("wrote lisp/src/data.lisp and lisp/tests/fixtures.lisp")


if __name__ == "__main__":
    main()
