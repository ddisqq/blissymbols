"""
Build the dictionary (Markdown + CSV) and the browsable symbol gallery from the database.

  dictionary/bliss_dictionary.md    every headword in the database, alphabetically, with its composition
  dictionary/bliss_dictionary.csv   the same data, one row per headword (spreadsheet friendly)
  gallery/index.html                searchable grid of all symbols: original 2D drawing + link to 3D

Depends on the symbol files produced by tools/build_symbols.py (svg/, 3d/, dictionary/symbols_index.csv).
Run:  python3 tools/build_dictionary.py
"""

import csv
import html
import os
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bliss_core as bc  # noqa: E402

REPO = bc.REPO


def display(name):
    """Database key -> readable English: underscores become spaces."""
    return name.replace("_", " ")


def names_of(key):
    return [n for n in key.split(",") if n]


def label(key, words, chars):
    """Readable label for a component: first name, then its other names separated by slashes."""
    ns = names_of(key)
    if not ns:
        return key
    return " / ".join(display(n) for n in ns)


def sort_key(key):
    return (key.lower(), key)


def letter_of(key):
    c = key[:1].upper()
    return c if c.isalpha() else "#"


def main():
    chardata, worddata = bc.load_data()
    B = bc.Bliss(chardata, worddata)
    words = worddata["words"]
    chars = chardata["chars"]

    # Map each symbol to its gallery/3D file names (written by build_symbols.py)
    import csv as _csv
    index = {}
    with open(os.path.join(REPO, "dictionary", "symbols_index.csv"), encoding="utf8") as f:
        for row in _csv.DictReader(f):
            index[row["database_key"]] = row

    entries = []
    unknown = []
    for key in sorted(words.keys(), key=sort_key):
        comps = words[key]
        base = []
        for p in B.expand_word([key])["chars"]:
            base.append(p["d"])
        base_plain = []
        for b in base:
            base_plain.append(b)
        for c in comps:
            if c not in words and c not in chars:
                unknown.append((key, c))
        entries.append({
            "key": key,
            "headword": display(names_of(key)[0]) if names_of(key) else key,
            "aliases": [display(n) for n in names_of(key)[1:]],
            "components": comps,
            "base": base_plain,
        })

    # ---------- CSV ----------
    csv_path = os.path.join(REPO, "dictionary", "bliss_dictionary.csv")
    with open(csv_path, "w", encoding="utf8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["headword", "also_called", "composed_of", "base_symbols", "symbol_count", "database_key"])
        for e in entries:
            w.writerow([
                e["headword"],
                "; ".join(e["aliases"]),
                " + ".join(label(c, words, chars) for c in e["components"]),
                " ".join(e["base"]),
                len(e["base"]),
                e["key"],
            ])

    # ---------- Markdown ----------
    md = []
    md.append("# Blissymbol dictionary\n")
    md.append(f"{len(entries)} headwords, built from `blissdata_words.js` and `blissdata_chars.js` "
              f"({len(chars)} symbols). Generated by `tools/build_dictionary.py`; do not edit by hand.\n")
    md.append("Each entry gives the English headword, any other English names for it (*also called*), "
              "and its composition: the words or symbols it is built from, joined with `+`, in the order "
              "they are written from left to right. Symbols marked as indicators "
              "(e.g. *indicator (description)*) are placed above or after the symbol they modify.\n")
    md.append("Full symbol list with sizes, usage counts and file links: [`symbols_index.csv`](symbols_index.csv). "
              "Symbol drawings: [`../svg/`](../svg/), 3D models: [`../3d/`](../3d/), "
              "browsable gallery: [`../gallery/index.html`](../gallery/index.html).\n")

    letters = OrderedDict()
    for e in entries:
        letters.setdefault(letter_of(e["key"]), []).append(e)
    md.append("Jump to: " + " · ".join(f"[{L}](#{L.lower() if L != '#' else 'other'})" for L in letters) + "\n")
    for L, items in letters.items():
        anchor = L.lower() if L != "#" else "other"
        md.append(f"\n## {L}  <a id=\"{anchor}\"></a>\n")
        for e in items:
            line = f"- **{e['headword']}**"
            if e["aliases"]:
                line += f" *(also: {', '.join(e['aliases'])})*"
            if e["components"]:
                line += " — " + " + ".join(label(c, words, chars) for c in e["components"])
            else:
                line += " — (no composition given)"
            line += f" · `{len(e['base'])} symbol{'s' if len(e['base']) != 1 else ''}`"
            md.append(line)

    with open(os.path.join(REPO, "dictionary", "bliss_dictionary.md"), "w", encoding="utf8") as f:
        f.write("\n".join(md) + "\n")

    # ---------- Gallery ----------
    rows = list(csv.DictReader(open(os.path.join(REPO, "dictionary", "symbols_index.csv"), encoding="utf8")))
    cards = []
    for r in rows:
        name = r["all_names"].replace(" | ", ", ")
        search = html.escape((r["all_names"] + " " + r["primary_name"]).lower(), quote=True)
        glb = "../" + r["glb_3d"] if r["glb_3d"] else ""
        cards.append(
            f'<article class="card" data-s="{search}">'
            f'<div class="pair">'
            f'<figure><img loading="lazy" src="../{r["svg"]}" alt="{html.escape(r["primary_name"])}"><figcaption>original</figcaption></figure>'
            f'<figure class="three"><a href="../3d/viewer.html?symbol={html.escape(os.path.basename(r["glb_3d"]), quote=True)}" title="Open in 3D viewer">'
            f'<span class="glb">3D</span></a><figcaption><a href="{html.escape(glb)}">.glb</a></figcaption></figure>'
            f'</div>'
            f'<h3>{html.escape(display(r["primary_name"]))}</h3>'
            f'<p class="meta">#{r["id"]} · {html.escape(name.replace("_", " "))}<br>'
            f'used in {r["used_in_headwords"]} headword{"s" if r["used_in_headwords"] != "1" else ""}</p>'
            f'</article>'
        )

    gallery = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Blissymbol gallery</title>
<style>
:root{{--bg:#fff;--fg:#111;--mut:#666;--line:#e3e3e3;--card:#fafafa;--acc:#1f5fbf}}
@media (prefers-color-scheme: dark){{:root:not([data-theme="light"]){{--bg:#121212;--fg:#eee;--mut:#9a9a9a;--line:#333;--card:#1c1c1c;--acc:#7fb0ff}}}}
:root[data-theme="dark"]{{--bg:#121212;--fg:#eee;--mut:#9a9a9a;--line:#333;--card:#1c1c1c;--acc:#7fb0ff}}
body{{margin:0;background:var(--bg);color:var(--fg);font:15px/1.4 system-ui,-apple-system,"Helvetica Neue",Arial,sans-serif}}
header{{position:sticky;top:0;background:var(--bg);border-bottom:1px solid var(--line);padding:12px 16px;z-index:2}}
h1{{font-size:18px;margin:0 0 8px}}
input{{width:100%;max-width:420px;padding:8px 10px;border:1px solid var(--line);border-radius:8px;background:var(--card);color:var(--fg);font:inherit}}
.count{{color:var(--mut);font-size:13px;margin-left:8px}}
main{{display:grid;grid-template-columns:repeat(auto-fill,minmax(200px,1fr));gap:12px;padding:16px}}
.card{{border:1px solid var(--line);border-radius:10px;background:var(--card);padding:10px}}
.card[hidden]{{display:none}}
.pair{{display:grid;grid-template-columns:1fr 1fr;gap:8px}}
figure{{margin:0;text-align:center}}
figure img{{width:100%;height:110px;object-fit:contain;background:#fff;border-radius:6px}}
figure figcaption{{font-size:12px;color:var(--mut);margin-top:4px}}
.three a{{display:block;height:110px;line-height:110px;border-radius:6px;background:linear-gradient(135deg,#eef4ff,#dfe9ff);color:var(--acc);font-weight:600;text-decoration:none}}
.three .glb{{font-size:22px;letter-spacing:.05em}}
h3{{font-size:14px;margin:8px 0 2px;word-break:break-word}}
.meta{{margin:0;font-size:12px;color:var(--mut)}}
a{{color:var(--acc)}}
</style></head>
<body>
<header>
<h1>Blissymbol gallery <span class="count" id="count">{len(rows)} symbols</span></h1>
<input id="q" type="search" placeholder="Filter by name, e.g. house, man, arrow…" autofocus>
</header>
<main id="grid">
{''.join(cards)}
</main>
<script>
const q=document.getElementById('q'),cards=[...document.querySelectorAll('.card')],count=document.getElementById('count');
q.addEventListener('input',()=>{{const t=q.value.trim().toLowerCase();let n=0;
for(const c of cards){{const hit=!t||c.dataset.s.includes(t);c.hidden=!hit;if(hit)n++;}}
count.textContent=n+' of {len(rows)} symbols';}});
</script>
</body></html>
"""
    # catalog for the 3D viewer (3d/viewer.html)
    import json
    catalog = [{"id": r["id"], "name": display(r["primary_name"]), "aliases": [display(n) for n in r["all_names"].split(" | ")[1:]],
                "glb": os.path.basename(r["glb_3d"]), "svg": "../" + r["svg"]} for r in rows if r["glb_3d"]]
    with open(os.path.join(REPO, "3d", "catalog.json"), "w", encoding="utf8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=0)

    os.makedirs(os.path.join(REPO, "gallery"), exist_ok=True)
    with open(os.path.join(REPO, "gallery", "index.html"), "w", encoding="utf8") as f:
        f.write(gallery)

    print(f"headwords: {len(entries)}  csv rows: {len(entries)}  gallery cards: {len(cards)}")
    print(f"components not found in database: {len(unknown)}")
    for k, c in unknown[:15]:
        print("   ", repr(k), "->", repr(c))


if __name__ == "__main__":
    main()
